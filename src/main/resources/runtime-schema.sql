CREATE TABLE IF NOT EXISTS GENESIS_SESSION (
 PRIMARY_ID CHAR(36) NOT NULL PRIMARY KEY,
 SESSION_ID CHAR(36) NOT NULL,
 CREATION_TIME BIGINT NOT NULL,
 LAST_ACCESS_TIME BIGINT NOT NULL,
 MAX_INACTIVE_INTERVAL INT NOT NULL,
 EXPIRY_TIME BIGINT NOT NULL,
 PRINCIPAL_NAME VARCHAR(100),
 UNIQUE KEY GENESIS_SESSION_IX1 (SESSION_ID),
 KEY GENESIS_SESSION_IX2 (EXPIRY_TIME),
 KEY GENESIS_SESSION_IX3 (PRINCIPAL_NAME)
);
CREATE TABLE IF NOT EXISTS GENESIS_SESSION_ATTRIBUTES (
 SESSION_PRIMARY_ID CHAR(36) NOT NULL,
 ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
 ATTRIBUTE_BYTES BLOB NOT NULL,
 PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
 FOREIGN KEY (SESSION_PRIMARY_ID) REFERENCES GENESIS_SESSION(PRIMARY_ID) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS genesis_rate_limits (
 key_hash CHAR(64) NOT NULL,
 bucket_id BIGINT NOT NULL,
 attempts INT NOT NULL,
 PRIMARY KEY (key_hash, bucket_id)
);
